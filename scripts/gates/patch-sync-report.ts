/** Markdown body builders for patch-sync.yml's PR / issues (plan §3.3.1-3). */
import { join } from "node:path"
import { readTextFileIfExists } from "../data/fs-cache"
import { snapshotDir } from "../data/paths"
import type { DemotionRecord } from "./demote"
import type { GateReport } from "./types"

function readReport(patch: string, file: string): string {
  return readTextFileIfExists(join(snapshotDir(patch), file)) ?? `_(${file} not found)_`
}

export function renderPrBody(args: {
  readonly current: string
  readonly target: string
  readonly gateReport: GateReport
  readonly demotions: readonly DemotionRecord[]
  readonly runUrl: string
}): string {
  const { current, target, gateReport, demotions, runUrl } = args
  const lines: string[] = [
    `Automated patch sync: \`${current}\` → \`${target}\`.`,
    "",
    `Generated by [patch-sync.yml](${runUrl}). Auto-merges once required checks pass.`,
    "",
  ]
  if (demotions.length > 0) {
    lines.push(
      "## Auto-demoted entities",
      "",
      "These modeled entities failed structural/coverage gates on this patch and were",
      "automatically set to `modeled: false` (greyed + badged in the UI) so the rest of",
      "the patch could still advance. See the linked issue for details.",
      "",
      "| Kind | Id | Name | Reason |",
      "|---|---|---|---|",
      ...demotions.map((d) => `| ${d.kind} | ${d.id} | ${d.name} | ${d.reason} |`),
      "",
    )
  }
  lines.push(
    "## Gate report",
    "",
    gateReport.gates
      .map((g) => `- ${g.passed ? "✅" : "❌"} **${g.name}** — ${g.summary}`)
      .join("\n"),
    "",
    "<details><summary>Diff report</summary>",
    "",
    readReport(target, "diff.md"),
    "",
    "</details>",
    "",
    "<details><summary>Coverage report</summary>",
    "",
    readReport(target, "COVERAGE.md"),
    "",
    "</details>",
  )
  return lines.join("\n")
}

export function renderDemotionIssueBody(args: {
  readonly target: string
  readonly demotions: readonly DemotionRecord[]
  readonly runUrl: string
}): string {
  const { target, demotions, runUrl } = args
  return [
    `Patch \`${target}\` synced successfully, but ${demotions.length} modeled entity(ies) failed`,
    "structural/coverage gates and were automatically demoted to `modeled: false`.",
    "",
    `Run: ${runUrl}`,
    "",
    "| Kind | Id | Name | Reason |",
    "|---|---|---|---|",
    ...demotions.map((d) => `| ${d.kind} | ${d.id} | ${d.name} | ${d.reason} |`),
    "",
    "A human should investigate whether this is a genuine CDragon mechanic change",
    "(bindings need updating) or transient data drift, and re-model the entity by",
    "removing its row from `data/demotions.json` once fixed.",
  ].join("\n")
}

export function renderFailureIssueBody(args: {
  readonly current: string
  readonly target: string
  readonly gateReport: GateReport | null
  readonly runUrl: string
  readonly errorMessage?: string
}): string {
  const { current, target, gateReport, runUrl, errorMessage } = args
  const lines: string[] = [
    `patch-sync failed to advance from \`${current}\` to \`${target}\`. \`main\` remains on \`${current}\`.`,
    "",
    `Run: ${runUrl}`,
    "",
  ]
  if (errorMessage !== undefined) {
    lines.push("## Error", "", "```", errorMessage, "```", "")
  }
  if (gateReport !== null) {
    lines.push(
      "## Gate report",
      "",
      gateReport.gates
        .map((g) => `- ${g.passed ? "✅" : "❌"} **${g.name}** — ${g.summary}`)
        .join("\n"),
    )
  }
  return lines.join("\n")
}
